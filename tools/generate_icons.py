#!/usr/bin/env python3
"""Registers every PNG in assets/mcduels/textures/icons as a chat glyph.

Each icon keeps the code point it was first given (tools/icons.json), so configs that
paste a glyph never change meaning. New PNGs get the next free code point from U+E900.
Writes the icon providers into assets/minecraft/font/default.json (rank glyphs are left
alone) and exports icons.yml, the name -> glyph list the MCDuels plugins ship.
"""
import json
import os

import generate_lang

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
ICONS = os.path.join(ROOT, 'assets', 'mcduels', 'textures', 'icons')
FONT = os.path.join(ROOT, 'assets', 'minecraft', 'font', 'default.json')
REGISTRY = os.path.join(ROOT, 'tools', 'icons.json')
EXPORT = os.path.join(ROOT, 'icons.yml')
FIRST = 0xE900
LAST = 0xF8FF
# Hand-made glyphs with their own providers in default.json (not in textures/icons), exported to icons.yml too.
LARGE_GLYPHS = {'logo': 0xE880}


def render_font(font):
    blocks = []
    for provider in font['providers']:
        lines = []
        for key, value in provider.items():
            if key == 'chars':
                text = '[%s]' % ', '.join('"%s"' % ''.join('\\u%04X' % ord(c) for c in chars) for chars in value)
            else:
                text = json.dumps(value)
            lines.append('            "%s": %s' % (key, text))
        blocks.append('        {\n' + ',\n'.join(lines) + '\n        }')
    return '{\n    "providers": [\n' + ',\n'.join(blocks) + '\n    ]\n}\n'


def main():
    registry = {}
    if os.path.exists(REGISTRY):
        with open(REGISTRY, encoding='utf-8') as source:
            registry = {name: int(code, 16) for name, code in json.load(source).items()}
    names = sorted(name[:-4] for name in os.listdir(ICONS) if name.endswith('.png'))
    used = set(registry.values())
    next_code = FIRST
    for name in names:
        if name in registry:
            continue
        while next_code in used:
            next_code += 1
        if next_code > LAST:
            raise SystemExit('No private-use code points left')
        registry[name] = next_code
        used.add(next_code)
    registry = {name: code for name, code in registry.items() if name in names}

    with open(FONT, encoding='utf-8') as source:
        font = json.load(source)
    providers = [p for p in font['providers'] if not p.get('file', '').startswith('mcduels:icons/')]
    for name, code in sorted(registry.items(), key=lambda entry: entry[1]):
        providers.append({
            'type': 'bitmap',
            'file': 'mcduels:icons/%s.png' % name,
            'ascent': 7,
            'height': 8,
            'chars': [chr(code)],
        })
    font['providers'] = providers
    with open(FONT, 'w', encoding='utf-8') as target:
        target.write(render_font(font))
    with open(REGISTRY, 'w', encoding='utf-8') as target:
        json.dump({name: '%04X' % code for name, code in sorted(registry.items(), key=lambda e: e[1])},
                  target, indent=2)
        target.write('\n')
    with open(EXPORT, 'w', encoding='utf-8') as target:
        target.write('# Generated by tools/generate_icons.py from the MCDuels resource pack.\n')
        target.write('# Use any icon in messages, chat and scoreboards as <icon:name> or :name:\n')
        target.write('icons:\n')
        for name, code in sorted({**LARGE_GLYPHS, **registry}.items(), key=lambda entry: entry[1]):
            target.write('  %s: "\\u%04X"\n' % (name, code))
    print('%d icons registered' % len(registry))
    generate_lang.main()


if __name__ == '__main__':
    main()
