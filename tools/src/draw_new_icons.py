def bars(n):
    rows = [['.'] * 16 for _ in range(16)]
    for b in range(5):
        h = 3 + b * 2; x0 = 1 + b * 3
        on = b < n
        for y in range(15 - h, 15):
            for x in range(x0, x0 + 2):
                rows[y][x] = '3' if on else '1'
    return '\n'.join(''.join(r) for r in rows)
