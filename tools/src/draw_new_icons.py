def draw(name, mask, ramps):
    if isinstance(ramps, str): ramps = {'*': ramps}
    im = Image.new('RGBA', (16, 16), (0, 0, 0, 0)); px = im.load()
    rows = [r for r in mask.strip('\n').split('\n')]
    assert len(rows) == 16, (name, len(rows))
    for y, row in enumerate(rows):
        row = row.ljust(16, '.')
        assert len(row) == 16, (name, y, row)
        for x, c in enumerate(row):
            if c == '.': continue
            if c == 'o': px[x, y] = O; continue
            if c.isdigit(): ramp = ramps.get('*'); shade = int(c)
            else:
                key = c.lower(); ramp = ramps[key]; shade = 3 if c.isupper() else 2
            px[x, y] = ramp_color(ramp, shade)
    im.save(os.path.join(OUT, name + '.png'))
def ramp_color(ramp, shade): return R[ramp][shade - 1] + (255,)

